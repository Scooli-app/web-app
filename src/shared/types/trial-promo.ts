/** Body of `GET /public/trial-promos/{code}` (ENG-360). */
export interface TrialPromoCheck {
  code: string;
  valid: boolean;
  /** Offer name set by the admin. Only on a valid code. */
  name?: string;
  /** Days the promo adds to the trial. Only on a valid code. */
  extraDays?: number;
  /** Length of the whole trial with the promo, in days. Only on a valid code. */
  totalTrialDays?: number;
  validUntil?: string | null;
}

/** 403 codes of `POST /users/me/trial/promo`. All of them are a silent refusal in the UI. */
export type TrialPromoErrorCode =
  | "promo_invalid"
  | "promo_not_eligible"
  | "promo_already_used"
  | "promo_exhausted";

const TRIAL_PROMO_ERROR_CODES: readonly TrialPromoErrorCode[] = [
  "promo_invalid",
  "promo_not_eligible",
  "promo_already_used",
  "promo_exhausted",
];

export function isTrialPromoErrorCode(value: unknown): value is TrialPromoErrorCode {
  return TRIAL_PROMO_ERROR_CODES.includes(value as TrialPromoErrorCode);
}

/** One row of `GET /admin/trial-promos` (also the body of the POST and PATCH). */
export interface AdminTrialPromo {
  code: string;
  name: string;
  extraDays: number;
  validFrom: string | null;
  validUntil: string | null;
  maxRedemptions: number | null;
  active: boolean;
  redemptions: number;
  /** Full sign-up link, exactly as the QR must encode it. */
  signupUrl: string;
  createdAt: string;
}

/** Body of `POST /admin/trial-promos`. A blank code is generated by the server from the name. */
export interface CreateTrialPromoRequest {
  code?: string;
  name: string;
  extraDays?: number;
  validFrom?: string | null;
  validUntil?: string | null;
  maxRedemptions?: number | null;
}

/** Body of `PATCH /admin/trial-promos/{code}`. The code is immutable. */
export interface UpdateTrialPromoRequest {
  name?: string;
  extraDays?: number;
  validFrom?: string | null;
  validUntil?: string | null;
  maxRedemptions?: number | null;
  active?: boolean;
}
