export type BrazilStateCode = (typeof BRAZIL_STATES)[number]["code"];

/** States whose own curriculum is loaded on top of the BNCC. The rest get the BNCC alone. */
export const STATES_WITH_CURRICULUM: readonly BrazilStateCode[] = ["MT", "MS"];

export function isBrazilStateCode(value: unknown): value is BrazilStateCode {
  return typeof value === "string" && BRAZIL_STATES.some((state) => state.code === value);
}
